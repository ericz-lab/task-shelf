export function tr(key: string, lang: Lang, vars?: Record<string, string | number>): string {
  const e = DICT[key];
  let s = e ? e[lang] : key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(String(v));
  return s;
}

/** Fill every [data-i18n], [data-i18n-ph], [data-i18n-aria], [data-i18n-title] under root. */
export function applyTranslations(root: ParentNode, lang: Lang): void {
  for (const el of root.querySelectorAll<HTMLElement>("[data-i18n]")) el.textContent = tr(el.dataset.i18n!, lang);
  for (const el of root.querySelectorAll<HTMLInputElement>("[data-i18n-ph]")) el.placeholder = tr(el.dataset.i18nPh!, lang);
  for (const el of root.querySelectorAll<HTMLElement>("[data-i18n-aria]")) el.setAttribute("aria-label", tr(el.dataset.i18nAria!, lang));
  for (const el of root.querySelectorAll<HTMLElement>("[data-i18n-title]")) el.title = tr(el.dataset.i18nTitle!, lang);
  document.title = tr("title", lang);
}
